<x-legal-page title="Conditions d'utilisation">
    <h2>1. Ce qu'est IDEE</h2>
    <p>IDEE met en relation des porteurs de projets avec les personnes qui peuvent les faire avancer : associés,
        contributeurs, experts, investisseurs et organisations d'appui. L'inscription, la publication d'un projet et les
        fiches pratiques sont gratuites.</p>

    <h2>2. Votre compte</h2>
    <ul>
        <li>Vous vous inscrivez avec votre téléphone ou votre e-mail, vérifié par un code à usage unique.</li>
        <li>Un compte correspond à une seule personne. Vous donnez des informations exactes et gardez votre téléphone pour vous.</li>
        <li>Vous acceptez la <a href="{{ route('legal.charter') }}">charte communautaire</a>.</li>
    </ul>

    <h2>3. Ce qu'IDEE ne fait jamais</h2>
    <ul>
        <li>Aucun argent entre membres ne transite par IDEE. Les montants recherchés sont indicatifs ; les fonds circulent directement entre les parties ou par des établissements agréés.</li>
        <li>IDEE ne propose pas de parts ni d'actions au public. Les informations sur une levée de fonds ne sont pas une offre au public.</li>
        <li>IDEE ne prend aucune commission sur les fonds levés et ne donne pas de conseil en investissement : elle ne dit jamais « investissez dans ce projet ».</li>
    </ul>

    <h2>4. Mises en relation</h2>
    <p>Une demande de contact porte sur un projet ou un besoin précis et se présente en au moins
        {{ config('idee.contact_message_min_length') }} caractères. Le nombre de demandes par semaine est limité contre les
        envois en masse. La messagerie s'ouvre quand les deux personnes se sont dites intéressées.</p>

    <h2>5. Vos contenus</h2>
    <ul>
        <li>Vous restez propriétaire de ce que vous publiez. Vous autorisez IDEE à l'afficher aux membres selon vos réglages : résumé public, détails et documents sur votre accord.</li>
        <li>Une idée publiée peut être copiée. IDEE date et scelle chaque version de votre projet, ce qui prouve son antériorité sans valoir titre de propriété. Une marque se protège auprès de l'OAPI.</li>
    </ul>

    <h2>6. Assistant IA</h2>
    <p>Les textes produits par l'assistant portent la mention « Généré avec l'IA, à vérifier ». L'assistant explique et
        guide ; il ne remplace ni un juriste, ni un expert-comptable, ni l'organisme compétent.</p>

    <h2>7. Offres payantes</h2>
    <ul>
        <li>Les prix sont indiqués en FCFA, toutes taxes comprises, et récapitulés avant le paiement.</li>
        <li>Les offres sont des packs prépayés, sans prélèvement automatique. Un reçu est émis pour chaque paiement.</li>
        <li>Une mise en avant payante porte la mention « Sponsorisé » et ne change ni le score ni l'ordre des recommandations.</li>
        <li>Une offre que vous n'avez pas commencé à utiliser peut être remboursée si vous le demandez dans les 7 jours suivant le paiement.</li>
    </ul>

    <h2>8. Responsabilité</h2>
    <p>Un badge de vérification correspond à une preuve contrôlée par l'équipe. Il ne garantit ni la solvabilité d'un
        investisseur ni la rentabilité d'un projet. Chaque membre reste responsable des accords qu'il conclut.</p>

    <h2>9. Suspension et suppression</h2>
    <p>Un compte qui ne respecte pas ces conditions ou la charte peut être suspendu ou exclu, avec un motif et une
        possibilité de recours. Vous pouvez supprimer votre compte à tout moment depuis votre profil.</p>

    <h2>10. Modifications et droit applicable</h2>
    <p>Quand ces conditions changent, IDEE vous demande de les accepter de nouveau. Elles sont soumises au droit sénégalais.</p>
